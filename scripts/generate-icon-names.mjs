#!/usr/bin/env node
/**
 * Generates the canonical list of valid `lc-icon` names and the inlined
 * Tabler subset.
 *
 * Sources (single source of truth each):
 *   1. The served Tabler set — every `.svg` under `@tabler/icons/icons/{outline,filled}`.
 *   2. `ICON_ALIASES` keys — documented Heroicon/Material aliases (icon/icon-aliases.ts).
 *   3. `INLINE_ICON_SVGS` — the hand-picked inline icons
 *      (internal/icon-set/icon-inline-svgs.ts since 3.6).
 *
 * Emits:
 *   - src/lib/icon-names/icon-names.data.ts → `ICON_NAMES` (compact, space-joined),
 *     in its own entry (`@lifecorner/angular-ui-kit/icon-names`) so production
 *     bundles leave it out (3.5, gap AS-15).
 *   - src/assets/icon-names.json       → the same array, shipped for tooling.
 *   - src/lib/internal/icon-set/icon-inline-tabler.data.ts → `INLINE_TABLER_SVGS`:
 *     the Tabler artwork of `INLINE_TABLER_NAMES` below, inlined at build time
 *     so these icons render offline, in prerendered HTML and without a request
 *     (3.3, gap G-7). Since 3.6 it is part of the lazy `internal/icon-set` entry.
 *   - src/lib/icons/icons.data.ts → one `ICON_*` constant per glyph of both
 *     maps plus `BUNDLED_ICONS`: the tree-shakable `@lifecorner/angular-ui-kit/icons`
 *     entry (3.6, gap AS-17). A copy, not an import: the eager and the lazy
 *     bundle graph must not share a module.
 *   - src/lib/icon/icon-inline-index.data.ts → the keys of both maps without
 *     markup, for `lc-icon`'s 3.5.1 lookup order (3.6, AS-17).
 *
 * Re-run after changing the alias/inline maps or bumping @tabler/icons:
 *   node scripts/generate-icon-names.mjs
 *
 * Unit tests (icon-catalog.spec.ts, icons.spec.ts) fail if the committed output
 * drifts from the maps, so a forgotten regen is caught in CI.
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join } from 'path';

const ROOT = process.cwd();
const ICON_DIR = join(ROOT, 'libs/angular-ui-kit/src/lib/icon');
const ICON_SET_DIR = join(ROOT, 'libs/angular-ui-kit/src/lib/internal/icon-set');
const ICONS_DIR = join(ROOT, 'libs/angular-ui-kit/src/lib/icons');
const ICON_NAMES_DIR = join(ROOT, 'libs/angular-ui-kit/src/lib/icon-names');
const TABLER_ROOT = join(ROOT, 'node_modules/@tabler/icons/icons');

/** Base names (without `.svg`) of every icon in the given Tabler variant dir. */
function readTablerNames(variant) {
  return readdirSync(join(TABLER_ROOT, variant))
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -'.svg'.length));
}

/**
 * Extract the top-level keys of an object literal from one of our own,
 * well-formatted source files. `valueStart` discriminates the entries we want
 * (aliases have string values → `'`/`"`; inline entries have object values → `{`).
 */
function extractKeys(dir, file, valueStart) {
  const src = readFileSync(join(dir, file), 'utf-8');
  const pattern =
    valueStart === '{'
      ? /^\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z0-9_$-]+))\s*:\s*\{\s*$/gm
      : /^\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z0-9_$-]+))\s*:\s*['"]/gm;
  const keys = [];
  let m;
  while ((m = pattern.exec(src)) !== null) keys.push(m[1] ?? m[2] ?? m[3]);
  return keys;
}

/**
 * Tabler icons inlined at build time (3.3, G-7): the names an app shell, a
 * sign-in flow, settings and a public website need before (or without) the
 * icon assets — plus the Tabler targets of the kit's own aliased defaults
 * (`x-circle` → `circle-x`, …). Aliases resolve to these too (`envelope` →
 * `mail`, `document-text` → `file-text`, `cog-6-tooth` → `settings`).
 * Keep the list short: every entry ships in every app's bundle.
 */
const INLINE_TABLER_NAMES = [
  // website
  'mail', 'file-text', 'file', 'arrow-right', 'arrow-left', 'external-link', 'world', 'menu-2', 'x',
  // app shell
  'users', 'user-plus', 'settings', 'logout', 'dots', 'wifi-off', 'chevron-right', 'chevron-left',
  // sign-in and account settings
  'login', 'key', 'password', 'shield-check', 'robot', 'plug-connected',
  'device-mobile', 'device-desktop', 'device-laptop', 'copy', 'share', 'link', 'trash',
  // the kit's status icons (alert, callout, toast) after alias resolution
  'info-circle', 'circle-check', 'alert-triangle', 'alert-circle', 'circle-x',
];

/** One Tabler SVG as a compact, class-free string (CSS sizes it, like the other inline icons). */
function readTablerSvg(variant, name) {
  const file = join(TABLER_ROOT, variant, `${name}.svg`);
  let svg;
  try {
    svg = readFileSync(file, 'utf-8');
  } catch {
    return null;
  }
  return svg
    .replace(/\s+/g, ' ')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none" ?\/>/g, '')
    .replace(/ (class|width|height)="[^"]*"/g, '')
    .replace(/\s*(\/?>)\s*/g, '$1')
    .trim();
}

/** A single-quoted TypeScript string literal. */
const tsString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const HEADER = `// AUTO-GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Regenerate with: node scripts/generate-icon-names.mjs
`;

/** `[name, { outline, solid? }]` of the Tabler subset, in INLINE_TABLER_NAMES order. */
function readInlineTabler() {
  return INLINE_TABLER_NAMES.map((name) => {
    const outline = readTablerSvg('outline', name);
    if (!outline) throw new Error(`[generate-icon-names] Tabler has no outline icon "${name}".`);
    const solid = readTablerSvg('filled', name);
    return [name, solid ? { outline, solid } : { outline }];
  });
}

function writeInlineTabler(tablerSvgs) {
  const entries = tablerSvgs.map(([name, svgs]) => {
    const variants = Object.entries(svgs).map(([variant, svg]) => `    ${variant}: ${tsString(svg)},`);
    return `  '${name}': {\n${variants.join('\n')}\n  },`;
  });
  const ts = `${HEADER}
import type { IconSetVariant as IconVariant } from './icon-set-types';

/**
 * Tabler icons inlined at build time (3.3, G-7), keyed by Tabler name, then
 * variant (\`solid\` only where Tabler has a filled icon). \`lc-icon\` uses them
 * after the hand-picked {@link INLINE_ICON_SVGS} and before any request, so
 * they render offline and in prerendered HTML. Since 3.6 (AS-17) they load
 * lazily with the rest of the kit's set, unless an app registers them.
 */
export const INLINE_TABLER_SVGS: Readonly<Record<string, Partial<Record<IconVariant, string>>>> = {
${entries.join('\n')}
};

/** The names in {@link INLINE_TABLER_SVGS}, in generator order. */
export const INLINE_TABLER_NAMES: readonly string[] = [
${INLINE_TABLER_NAMES.map((n) => `  '${n}',`).join('\n')}
];
`;
  writeFileSync(join(ICON_SET_DIR, 'icon-inline-tabler.data.ts'), ts);
}

/** `[name, { outline, solid }]` of the hand-picked map, in source order (values are single-quoted strings). */
function readHandPicked() {
  const src = readFileSync(join(ICON_SET_DIR, 'icon-inline-svgs.ts'), 'utf-8');
  const entries = [];
  for (const [, name, body] of src.matchAll(/^ {2}'?([a-z0-9-]+)'?: \{\n([\s\S]*?)^ {2}\},?$/gm)) {
    const svgs = {};
    for (const [, variant, svg] of body.matchAll(/(outline|solid):\s*'((?:[^'\\]|\\.)*)'/g)) svgs[variant] = svg;
    if (!svgs.outline || !svgs.solid) throw new Error(`[generate-icon-names] "${name}" lacks an outline or solid glyph.`);
    entries.push([name, svgs]);
  }
  return entries;
}

const constantName = (name, variant) => `ICON_${name.toUpperCase().replace(/-/g, '_')}${variant === 'solid' ? '_SOLID' : ''}`;

/** The `@lifecorner/angular-ui-kit/icons` constants (3.6, AS-17). */
function writeIconConstants(handPicked, tablerSvgs) {
  const constants = (entries) =>
    entries.flatMap(([name, svgs]) =>
      Object.entries(svgs).map(
        ([variant, svg]) =>
          `export const ${constantName(name, variant)}: LcIconDefinition = { name: '${name}', variant: '${variant}', svg: ${tsString(svg)} };`,
      ),
    );
  const all = [...handPicked, ...tablerSvgs];
  const count = all.reduce((n, [, svgs]) => n + Object.keys(svgs).length, 0);
  const list = all.map(([name, svgs]) => `  ${Object.keys(svgs).map((variant) => constantName(name, variant)).join(', ')},`);
  const ts = `${HEADER}
import type { LcIconDefinition } from '@lifecorner/angular-ui-kit/icon';

// The hand-picked set, keyed like 3.5.1's INLINE_ICON_SVGS.

${constants(handPicked).join('\n')}

// The Tabler icons inlined at build time (3.3, G-7), keyed like 3.5.1's INLINE_TABLER_SVGS.

${constants(tablerSvgs).join('\n')}

/**
 * Every glyph above (${count}): \`provideLcIcons(BUNDLED_ICONS)\` restores the
 * synchronous rendering of 3.5.1 for every inline name, e.g. in tests or
 * Storybook. An app that imports it bundles all of them.
 */
export const BUNDLED_ICONS: readonly LcIconDefinition[] = [
${list.join('\n')}
];
`;
  writeFileSync(join(ICONS_DIR, 'icons.data.ts'), ts);
}

/** lc-icon's key index: the inline names without markup (3.6, AS-17). */
function writeInlineIndex(handPicked, tablerSvgs) {
  const keys = (entries) => entries.map(([name]) => name).join(' ');
  const ts = `${HEADER}
/**
 * The keys of the kit's inline set without their markup (3.6, AS-17): which
 * names rendered from bundled markup in 3.5.1. \`lc-icon\` needs them to keep
 * 3.5.1's lookup order (and \`isInlineIconName\`) while the markup itself lives
 * in \`@lifecorner/angular-ui-kit/icons\` and the lazy \`internal/icon-set\`.
 * Space-joined, split on first use.
 */

/** The hand-picked keys (\`INLINE_ICON_SVGS\`); each has an outline and a solid glyph. */
export const INLINE_HAND_KEYS =
  '${keys(handPicked)}';

/** The inlined Tabler keys (\`INLINE_TABLER_SVGS\`) with an outline glyph. */
export const INLINE_TABLER_OUTLINE_KEYS =
  '${keys(tablerSvgs)}';

/** The inlined Tabler keys with a solid (filled) glyph. */
export const INLINE_TABLER_SOLID_KEYS =
  '${keys(tablerSvgs.filter(([, svgs]) => svgs.solid))}';
`;
  writeFileSync(join(ICON_DIR, 'icon-inline-index.data.ts'), ts);
}

const tabler = [...readTablerNames('outline'), ...readTablerNames('filled')];
const aliasKeys = extractKeys(ICON_DIR, 'icon-aliases.ts', "'");
const inlineKeys = extractKeys(ICON_SET_DIR, 'icon-inline-svgs.ts', '{');

if (aliasKeys.length === 0 || inlineKeys.length === 0) {
  throw new Error(
    `[generate-icon-names] Failed to extract keys (aliases=${aliasKeys.length}, inline=${inlineKeys.length}). Aborting to avoid writing an incomplete list.`
  );
}

const names = [...new Set([...tabler, ...aliasKeys, ...inlineKeys])].sort();

const ts = `// AUTO-GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Regenerate with: node scripts/generate-icon-names.mjs

/**
 * The canonical set of valid \`lc-icon\` names: every served Tabler icon plus
 * every documented alias ({@link ICON_ALIASES}) and inlined icon.
 * Stored space-joined and split at load to keep the bundle compact.
 */
export const ICON_NAMES: readonly string[] = Object.freeze(
  '${names.join(' ')}'.split(' ')
);
`;

writeFileSync(join(ICON_NAMES_DIR, 'icon-names.data.ts'), ts);
writeFileSync(
  join(ROOT, 'libs/angular-ui-kit/src/assets/icon-names.json'),
  JSON.stringify(names, null, 0) + '\n'
);

const tablerSvgs = readInlineTabler();
const handPicked = readHandPicked();
writeInlineTabler(tablerSvgs);
writeIconConstants(handPicked, tablerSvgs);
writeInlineIndex(handPicked, tablerSvgs);

console.log(
  `[generate-icon-names] wrote ${names.length} names and ${INLINE_TABLER_NAMES.length} inlined Tabler icons ` +
    `(${tabler.length} tabler + ${aliasKeys.length} aliases + ${inlineKeys.length} inline, deduped), ` +
    `the ICON_* constants and lc-icon's key index.`
);

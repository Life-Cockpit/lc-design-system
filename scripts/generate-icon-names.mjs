#!/usr/bin/env node
/**
 * Generates the canonical list of valid `lc-icon` names.
 *
 * Sources (single source of truth each):
 *   1. The served Tabler set — every `.svg` under `@tabler/icons/icons/{outline,filled}`.
 *   2. `ICON_ALIASES` keys — documented Heroicon/Material aliases (icon-aliases.ts).
 *   3. `INLINE_ICON_SVGS` keys — inlined common icons (icon-inline-svgs.ts).
 *
 * Emits:
 *   - src/lib/icon/icon-names.data.ts  → `ICON_NAMES` (compact, space-joined).
 *   - src/assets/icon-names.json       → the same array, shipped for tooling.
 *
 * Re-run after changing the alias/inline maps or bumping @tabler/icons:
 *   node scripts/generate-icon-names.mjs
 *
 * A unit test (icon-catalog.spec.ts) fails if the committed output drifts from
 * the maps, so a forgotten regen is caught in CI.
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join } from 'path';

const ROOT = process.cwd();
const ICON_DIR = join(ROOT, 'libs/angular-ui-kit/src/lib/icon');
const TABLER_ROOT = join(ROOT, 'node_modules/@tabler/icons/icons');

/** Base names (without `.svg`) of every icon in the given Tabler variant dir. */
function readTablerNames(variant) {
  return readdirSync(join(TABLER_ROOT, variant))
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -'.svg'.length));
}

/**
 * Extract the top-level keys of an object literal from one of our own,
 * well-formatted source files. `valueStart` discriminates the entries we want
 * (aliases have string values → `'`/`"`; inline entries have object values → `{`).
 */
function extractKeys(file, valueStart) {
  const src = readFileSync(join(ICON_DIR, file), 'utf-8');
  const pattern =
    valueStart === '{'
      ? /^\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z0-9_$-]+))\s*:\s*\{\s*$/gm
      : /^\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z0-9_$-]+))\s*:\s*['"]/gm;
  const keys = [];
  let m;
  while ((m = pattern.exec(src)) !== null) keys.push(m[1] ?? m[2] ?? m[3]);
  return keys;
}

const tabler = [...readTablerNames('outline'), ...readTablerNames('filled')];
const aliasKeys = extractKeys('icon-aliases.ts', "'");
const inlineKeys = extractKeys('icon-inline-svgs.ts', '{');

if (aliasKeys.length === 0 || inlineKeys.length === 0) {
  throw new Error(
    `[generate-icon-names] Failed to extract keys (aliases=${aliasKeys.length}, inline=${inlineKeys.length}). Aborting to avoid writing an incomplete list.`
  );
}

const names = [...new Set([...tabler, ...aliasKeys, ...inlineKeys])].sort();

const ts = `// AUTO-GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Regenerate with: node scripts/generate-icon-names.mjs

/**
 * The canonical set of valid \`lc-icon\` names: every served Tabler icon plus
 * every documented alias ({@link ICON_ALIASES}) and inlined icon.
 * Stored space-joined and split at load to keep the bundle compact.
 */
export const ICON_NAMES: readonly string[] = Object.freeze(
  '${names.join(' ')}'.split(' ')
);
`;

writeFileSync(join(ICON_DIR, 'icon-names.data.ts'), ts);
writeFileSync(
  join(ROOT, 'libs/angular-ui-kit/src/assets/icon-names.json'),
  JSON.stringify(names, null, 0) + '\n'
);

console.log(
  `[generate-icon-names] wrote ${names.length} names ` +
    `(${tabler.length} tabler + ${aliasKeys.length} aliases + ${inlineKeys.length} inline, deduped).`
);

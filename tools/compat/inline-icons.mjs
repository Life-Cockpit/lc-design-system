/**
 * Every inline icon name × variant the kit ships, read from the kit's sources
 * (the hand-picked `INLINE_ICON_SVGS` and the generated `INLINE_TABLER_SVGS`),
 * not from `ICON_NAMES`. The compat fixture renders them all on `/tt/icons`
 * (request 001, AC-10 a) and check-trusted-types.mjs expects one `<svg>` each.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/** `[name, variant][]` in source order; `solid` only where the kit ships one. */
export function inlineIcons(root) {
  // Since 3.6 (AS-17) both maps live in the lazy internal/icon-set entry.
  const dir = join(root, 'libs/angular-ui-kit/src/lib/internal/icon-set');
  const icons = [];
  for (const file of ['icon-inline-svgs.ts', 'icon-inline-tabler.data.ts']) {
    const src = readFileSync(join(dir, file), 'utf8');
    // Top-level entries: `  name: {` or `  'name': {`, then their variant keys up to the closing `  },`.
    for (const entry of src.matchAll(/^ {2}'?([a-z0-9-]+)'?: \{\n([\s\S]*?)^ {2}\},?$/gm)) {
      const [, name, body] = entry;
      for (const variant of ['outline', 'solid']) {
        if (new RegExp(`^ {4}${variant}:`, 'm').test(body)) icons.push([name, variant]);
      }
    }
  }
  if (icons.length < 100) throw new Error(`inline-icons: found only ${icons.length} inline icons in ${dir}`);
  return icons;
}

/** The fixture's `inline-icons.ts`. */
export function inlineIconsModule(root) {
  const rows = inlineIcons(root).map(([name, variant]) => `  ['${name}', '${variant}'],`);
  return `// Generated by tools/compat/inline-icons.mjs from the kit's sources (request 001, AC-10 a).
export const INLINE_ICONS: ReadonlyArray<readonly [string, 'outline' | 'solid']> = [
${rows.join('\n')}
];
`;
}
